export function getFighterById(id) {
    return REAL_FIGHTERS.find(fighter => fighter.id === id) || null;
}

export function getFightersByOrganization(organizationId) {
    return REAL_FIGHTERS.filter(
        fighter => fighter.organization === organizationId
    );
}

export function getFightersByWeightClass(weightClassId) {
    return REAL_FIGHTERS.filter(
        fighter => fighter.weightClass === weightClassId
    );
}

export function getFightersByCountry(countryId) {
    return REAL_FIGHTERS.filter(
        fighter => fighter.country === countryId
    );
}
